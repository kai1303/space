import { test,before,after } from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { Pool } from 'pg';
import { migrate } from '@space/postgres/migrate';
import { bootstrap } from '@space/postgres/bootstrap';
import { WorkspaceStore } from '@space/postgres/workspace';
import { WorkspaceSettingsStore } from '@space/postgres/workspace-settings';
import { ChatStore } from '@space/postgres/chat';
const url=process.env.TEST_DATABASE_URL;if(!url)throw new Error('TEST_DATABASE_URL required');
const schema=`membership_${randomBytes(8).toString('hex')}`,admin=new Pool({connectionString:url}),pool=new Pool({connectionString:url,options:`-c search_path=${schema}`});
const workspaces=new WorkspaceStore(pool),chat=new ChatStore(pool),settings=new WorkspaceSettingsStore(pool);
before(async()=>{await admin.query(`CREATE SCHEMA ${schema}`);await migrate(pool);});
after(async()=>{await pool.end();await admin.query(`DROP SCHEMA ${schema} CASCADE`);await admin.end();});
test('primary ownership transfers atomically to active full members and protects the current primary owner',async()=>{
 const a=await bootstrap(pool);
 assert.equal((await workspaces.read(a.owner_id,a.workspace_id)).primary_owner_id,a.owner_id);
 await assert.rejects(workspaces.transferOwnership(a.collaborator_id,a.workspace_id,{user_id:a.collaborator_id}),{status:403});
 await workspaces.changeRole(a.owner_id,a.workspace_id,a.collaborator_id,{role:'owner'});
 await assert.rejects(workspaces.removeMember(a.owner_id,a.workspace_id,a.owner_id),{code:'transfer_ownership_first'});
 await workspaces.transferOwnership(a.owner_id,a.workspace_id,{user_id:a.collaborator_id});
 await workspaces.changeRole(a.owner_id,a.workspace_id,a.owner_id,{role:'member'});
 assert.equal((await workspaces.read(a.collaborator_id,a.workspace_id)).primary_owner_id,a.collaborator_id);
 await assert.rejects(workspaces.transferOwnership(a.owner_id,a.workspace_id,{user_id:a.owner_id}),{status:403});
});
test('guests only discover assigned channels and peers, cannot join/create/manage, and single-channel assignments resist races',async()=>{
 const a=await bootstrap(pool),outsider=await bootstrap(pool);
 await workspaces.addMember(a.owner_id,a.workspace_id,{user_id:outsider.owner_id,role:'member'});
 const one=await chat.createChannel(a.owner_id,a.workspace_id,{name:'assigned',private:false});
 const two=await chat.createChannel(a.owner_id,a.workspace_id,{name:'other',private:false});
 await pool.query('DELETE FROM channel_members WHERE workspace_id=$1 AND user_id=$2',[a.workspace_id,a.collaborator_id]);
 await pool.query("UPDATE workspace_members SET guest_type='single' WHERE workspace_id=$1 AND user_id=$2",[a.workspace_id,a.collaborator_id]);
 const outcomes=await Promise.allSettled([one,two].map(ch=>chat.addMember(a.owner_id,ch.id,{user_id:a.collaborator_id})));
 assert.equal(outcomes.filter(o=>o.status==='fulfilled').length,1);
 const channels=await chat.channels(a.collaborator_id,a.workspace_id);
 assert.equal(channels.items.length,1);
 await assert.rejects(chat.join(a.collaborator_id,channels.items[0]!.id===one.id?two.id:one.id),{status:403});
 await assert.rejects(chat.createChannel(a.collaborator_id,a.workspace_id,{name:'forbidden',private:false}),{status:403});
 await assert.rejects(chat.addMember(a.collaborator_id,channels.items[0]!.id,{user_id:outsider.owner_id}),{status:403});
 const people=await chat.directMessages.people(a.collaborator_id,a.workspace_id);
 assert.ok(people.items.some(p=>p.id===a.owner_id));assert.ok(!people.items.some(p=>p.id===outsider.owner_id));
 const members=await workspaces.directory(a.collaborator_id,a.workspace_id);
 assert.ok(!members.items.some(m=>m.user_id===outsider.owner_id));
 await assert.rejects(chat.directMessages.open(a.collaborator_id,a.workspace_id,{user_id:outsider.owner_id}),{status:403});
 await assert.rejects(chat.directMessages.open(outsider.owner_id,a.workspace_id,{user_id:a.collaborator_id}),{status:403});
 await chat.directMessages.open(a.collaborator_id,a.workspace_id,{user_id:a.owner_id});
 await assert.rejects(workspaces.changeRole(a.owner_id,a.workspace_id,a.collaborator_id,{role:'admin'}),{code:'guest_role_conflict'});
});
test('directory sorting stays paginated, visibility follows settings and CSV export prevents formula execution',async()=>{
 const a=await bootstrap(pool);
 await pool.query('UPDATE users SET display_name=$1,email=$2 WHERE id=$3',['=cmd','member@example.test',a.collaborator_id]);
 const first=await workspaces.directory(a.owner_id,a.workspace_id,{sort:'name',limit:'1'});
 const second=await workspaces.directory(a.owner_id,a.workspace_id,{sort:'name',limit:'1',after:first.next_cursor});
 assert.equal(new Set([...first.items,...second.items].map(m=>m.user_id)).size,2);
 assert.ok(!(await workspaces.directory(a.collaborator_id,a.workspace_id)).items.some(m=>'email' in m));
 await settings.update(a.owner_id,a.workspace_id,{revision:'0',email_visibility:'members',create_channel_permission:'admins'});
 assert.ok((await workspaces.directory(a.collaborator_id,a.workspace_id)).items.some(m=>m.email==='member@example.test'));
 await assert.rejects(chat.createChannel(a.collaborator_id,a.workspace_id,{name:'denied',private:false}),{status:403});
 assert.match(await workspaces.exportMembers(a.owner_id,a.workspace_id),/"'=cmd"/);
 await assert.rejects(workspaces.exportMembers(a.collaborator_id,a.workspace_id),{status:403});
 const revision=(await settings.read(a.owner_id,a.workspace_id)).revision;
 await workspaces.rename(a.owner_id,a.workspace_id,{name:'New'});
 await assert.rejects(settings.update(a.owner_id,a.workspace_id,{revision,name:'Stale'}),{code:'settings_changed_reload'});
});
test('joined-date cursor preserves PostgreSQL microseconds without repeating the anchor',async()=>{
 const a=await bootstrap(pool);
 await pool.query("UPDATE workspace_members SET joined_at='2026-01-01T00:00:00.000001Z' WHERE workspace_id=$1 AND user_id=$2",[a.workspace_id,a.owner_id]);
 await pool.query("UPDATE workspace_members SET joined_at='2026-01-01T00:00:00.000002Z' WHERE workspace_id=$1 AND user_id=$2",[a.workspace_id,a.collaborator_id]);
 const first=await workspaces.directory(a.owner_id,a.workspace_id,{sort:'joined',limit:'1'});
 const second=await workspaces.directory(a.owner_id,a.workspace_id,{sort:'joined',limit:'1',after:first.next_cursor});
 assert.equal(first.items[0]!.user_id,a.owner_id);assert.equal(second.items[0]!.user_id,a.collaborator_id);assert.equal(second.next_cursor,null);
});
