import {test,before,after} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {Pool} from 'pg';
import {bootstrap} from '@space/postgres/bootstrap';
import {migrate} from '@space/postgres/migrate';
import {WorkspaceHubStore} from '@space/postgres/workspace-hub';
const schema=`session_stars_${randomUUID().replaceAll('-','')}`;
const admin=new Pool({connectionString:process.env.TEST_DATABASE_URL});
const pool=new Pool({connectionString:process.env.TEST_DATABASE_URL,options:`-c search_path=${schema}`});
const store=new WorkspaceHubStore(pool);
before(async()=>{assert.ok(process.env.TEST_DATABASE_URL);await admin.query(`CREATE SCHEMA ${schema}`);await migrate(pool);});
after(async()=>{await pool.end();await admin.query(`DROP SCHEMA ${schema} CASCADE`);await admin.end();});
test('session stars persist, remain personal, paginate, and recheck channel and workspace access',async()=>{
 const a=await bootstrap(pool),b=await bootstrap(pool),ids=[randomUUID(),randomUUID()].sort();
 for(const id of ids)await pool.query("INSERT INTO agent_sessions(id,workspace_id,installation_id,origin_thread_id,title,managed) VALUES($1,$2,$3,$4,'Review README',true)",[id,a.workspace_id,a.installation_id,a.thread_id]);
 const beforeDelivery=Number((await pool.query('SELECT count(*) AS count FROM chat_delivery_outbox')).rows[0].count);
 await Promise.all(Array.from({length:6},()=>store.starSession(a.owner_id,a.workspace_id,ids[0]!,{active:true})));
 assert.equal(Number((await pool.query('SELECT count(*) AS count FROM chat_delivery_outbox')).rows[0].count),beforeDelivery+1);
 assert.deepEqual(await store.sessionStarState(a.owner_id,a.workspace_id,ids[0]!),{active:true});
 assert.equal((await new WorkspaceHubStore(pool).starredSessions(a.owner_id,a.workspace_id)).items.length,1);
 assert.equal((await store.starredSessions(a.collaborator_id,a.workspace_id)).items.length,0);
 const item=(await store.starredSessions(a.owner_id,a.workspace_id)).items[0]!;
 assert.equal(item.session?.agent_name,'Mock echo agent');assert.equal(item.session?.channel_id,a.channel_id);
 await store.starSession(a.owner_id,a.workspace_id,ids[1]!,{active:true});
 const first=await store.starredSessions(a.owner_id,a.workspace_id,{limit:'1'});
 assert.equal(first.items[0]!.id,ids[0]);assert.equal(first.next_cursor,ids[0]);
 assert.equal((await store.starredSessions(a.owner_id,a.workspace_id,{after:first.next_cursor,limit:'1'})).items[0]!.id,ids[1]);
 await store.starSession(a.owner_id,a.workspace_id,ids[0]!,{active:false});
 await store.starSession(a.owner_id,a.workspace_id,ids[0]!,{active:false});
 assert.deepEqual(await store.sessionStarState(a.owner_id,a.workspace_id,ids[0]!),{active:false});
 await assert.rejects(()=>store.starSession(b.owner_id,a.workspace_id,ids[0]!,{active:true}),/not_found/);
 await assert.rejects(()=>store.starSession(a.owner_id,b.workspace_id,ids[0]!,{active:true}),/not_found/);
 await assert.rejects(()=>store.starSession(a.owner_id,a.workspace_id,ids[0]!,{active:'yes'}),/invalid_active/);
 await pool.query('DELETE FROM channel_members WHERE channel_id=$1 AND user_id=$2',[a.channel_id,a.owner_id]);
 assert.equal((await store.starredSessions(a.owner_id,a.workspace_id)).items.length,0);
 await assert.rejects(()=>store.sessionStarState(a.owner_id,a.workspace_id,ids[1]!),/not_found/);
 await assert.rejects(()=>store.starSession(a.owner_id,a.workspace_id,ids[1]!,{active:false}),/not_found/);
 await pool.query("UPDATE workspace_members SET role='owner' WHERE workspace_id=$1 AND user_id=$2",[a.workspace_id,a.collaborator_id]);
 await pool.query('UPDATE workspaces SET primary_owner_id=$2 WHERE id=$1',[a.workspace_id,a.collaborator_id]);
 await pool.query('UPDATE workspace_members SET active=false WHERE workspace_id=$1 AND user_id=$2',[a.workspace_id,a.owner_id]);
 await assert.rejects(()=>store.starredSessions(a.owner_id,a.workspace_id),/not_found/);
});
