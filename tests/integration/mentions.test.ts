import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import { Pool } from 'pg';
import { bootstrap } from '@space/postgres/bootstrap';
import { migrate } from '@space/postgres/migrate';
import { PostgresStore } from '@space/postgres/store';
import { createApi } from '@space/server/api';
const schema=`mentions_${randomBytes(8).toString('hex')}`;
const admin=new Pool({connectionString:process.env.TEST_DATABASE_URL});
const pool=new Pool({connectionString:process.env.TEST_DATABASE_URL,options:`-c search_path=${schema}`});
const app=createApi(new PostgresStore(pool),{allowDevelopmentTokens:true});
before(async()=>{if(!process.env.TEST_DATABASE_URL)throw Error('TEST_DATABASE_URL required');await admin.query(`CREATE SCHEMA ${schema}`);await migrate(pool);await app.ready();});
after(async()=>{await app.close();await pool.end();await admin.query(`DROP SCHEMA ${schema} CASCADE`);await admin.end();});
async function api(token:string,method:'GET'|'POST'|'PATCH',path:string,payload?:object,status=200){const r=await app.inject({method,url:`/v1${path}`,headers:{authorization:`Bearer ${token}`},payload});assert.equal(r.statusCode,status,`${path}: ${r.body}`);return r.json();}
const document=(mention:object,label:string)=>({ops:[{insert:`@${label}`,attributes:{mention}},{insert:' hello\n'}]});
test('directory is scoped; mentions canonicalize stable identities and notify exactly once',async()=>{
 const a=await bootstrap(pool),other=await bootstrap(pool);
 const options=await api(a.owner_token,'GET',`/channels/${a.channel_id}/mentions?q=collab`);
 assert.equal(options.items[0].id,a.collaborator_id);
 await api(other.owner_token,'GET',`/channels/${a.channel_id}/mentions`,undefined,404);
 const mention={kind:'user',id:a.collaborator_id,label:'Old name'};
 const input={client_message_id:randomUUID(),text:'@Old name hello',document:document(mention,'Old name')};
 const message=await api(a.owner_token,'POST',`/channels/${a.channel_id}/messages`,input,201);
 assert.equal(message.text,'@Demo collaborator hello');
 assert.equal(message.document.ops[0].attributes.mention.id,a.collaborator_id);
 await api(a.owner_token,'POST',`/channels/${a.channel_id}/messages`,input,201);
 const activity=await api(a.collaborator_token,'GET',`/workspaces/${a.workspace_id}/mentions`);
 assert.equal(activity.items.length,1);assert.equal(activity.unread_count,1);
 assert.equal(activity.items[0].message_id,message.id);
 await api(a.collaborator_token,'POST',`/workspaces/${a.workspace_id}/mentions/${activity.items[0].id}/read`,{});
 assert.equal((await api(a.collaborator_token,'GET',`/workspaces/${a.workspace_id}/mentions`)).unread_count,0);
 await api(a.owner_token,'POST',`/workspaces/${a.workspace_id}/mentions/${activity.items[0].id}/read`,{},404);
 const invalid={kind:'user',id:other.owner_id,label:'Other'};
 await api(a.owner_token,'POST',`/channels/${a.channel_id}/messages`,{client_message_id:randomUUID(),text:'@Other hello',document:document(invalid,'Other')},404);
});
test('broadcasts respect presence, threads, general channel identity, pause and admin restrictions',async()=>{
 const a=await bootstrap(pool);
 const send=(kind:string,extra={})=>api(a.owner_token,'POST',`/channels/${a.channel_id}/messages`,{client_message_id:randomUUID(),text:`@${kind} hello`,document:document({kind:'broadcast',id:kind,label:kind},kind),...extra},201);
 await pool.query('UPDATE users SET presence=$1 WHERE id=$2',['away',a.collaborator_id]);
 await send('here');assert.equal((await api(a.collaborator_token,'GET',`/workspaces/${a.workspace_id}/mentions`)).items.length,0);
 const root=await send('channel');assert.equal((await api(a.collaborator_token,'GET',`/workspaces/${a.workspace_id}/mentions`)).items.length,1);
 await send('channel',{thread_id:root.thread_id});assert.equal((await api(a.collaborator_token,'GET',`/workspaces/${a.workspace_id}/mentions`)).items.length,1);
 await send('everyone');
 await api(a.owner_token,'PATCH',`/channels/${a.channel_id}`,{name:'lobby'});
 await send('everyone');
 await api(a.collaborator_token,'PATCH',`/workspaces/${a.workspace_id}/mention-settings`,{paused_until:new Date(Date.now()+3600000).toISOString()});
 await send('channel');const inbox=await api(a.collaborator_token,'GET',`/workspaces/${a.workspace_id}/mentions`);assert.equal(inbox.items[0].silent,true);assert.equal(inbox.unread_count,4);
 await api(a.owner_token,'PATCH',`/workspaces/${a.workspace_id}/mention-settings`,{broadcast_permission:'admins'});
 await api(a.collaborator_token,'PATCH',`/workspaces/${a.workspace_id}/mention-settings`,{broadcast_permission:'all'},403);
 await api(a.collaborator_token,'POST',`/channels/${a.channel_id}/messages`,{client_message_id:randomUUID(),text:'@channel hello',document:document({kind:'broadcast',id:'channel',label:'channel'},'channel')},403);
});
test('private mentions never grant channel access and revocation removes activity',async()=>{
 const a=await bootstrap(pool);
 const ch=await api(a.owner_token,'POST',`/workspaces/${a.workspace_id}/channels`,{name:'secret',private:true},201);
 assert.ok(!(await api(a.owner_token,'GET',`/channels/${ch.id}/mentions`)).items.some((m:any)=>m.id===a.collaborator_id));
 const mention={kind:'user',id:a.collaborator_id,label:'Demo collaborator'};
 const send=()=>api(a.owner_token,'POST',`/channels/${ch.id}/messages`,{client_message_id:randomUUID(),text:'@Demo collaborator hello',document:document(mention,mention.label)},201);
 await send();assert.equal((await api(a.collaborator_token,'GET',`/workspaces/${a.workspace_id}/mentions`)).items.length,0);
 await api(a.owner_token,'POST',`/channels/${ch.id}/members`,{user_id:a.collaborator_id},201);await send();
 assert.equal((await api(a.collaborator_token,'GET',`/workspaces/${a.workspace_id}/mentions`)).items.length,1);
 await pool.query('DELETE FROM channel_members WHERE channel_id=$1 AND user_id=$2',[ch.id,a.collaborator_id]);
 assert.equal((await api(a.collaborator_token,'GET',`/workspaces/${a.workspace_id}/mentions`)).items.length,0);
});
test('confirmation is enforced on the server and direct thread mentions still notify',async()=>{
 const a=await bootstrap(pool);
 const extra=Array.from({length:4},()=>randomUUID());
 for(const id of extra){await pool.query('INSERT INTO users(id,display_name) VALUES($1,$2)',[id,'Teammate']);await pool.query("INSERT INTO workspace_members(workspace_id,user_id,role) VALUES($1,$2,'member')",[a.workspace_id,id]);await pool.query('INSERT INTO channel_members(workspace_id,channel_id,user_id) VALUES($1,$2,$3)',[a.workspace_id,a.channel_id,id]);}
 const input={client_message_id:randomUUID(),text:'@channel hello',document:document({kind:'broadcast',id:'channel',label:'channel'},'channel')};
 await api(a.owner_token,'POST',`/channels/${a.channel_id}/messages`,input,409);
 assert.equal((await pool.query('SELECT count(*)::int AS n FROM messages WHERE channel_id=$1',[a.channel_id])).rows[0].n,0);
 const root=await api(a.owner_token,'POST',`/channels/${a.channel_id}/messages`,{...input,broadcast_confirmed:true},201);
 await api(a.owner_token,'POST',`/channels/${a.channel_id}/messages`,{...input,broadcast_confirmed:true},201);
 const mention={kind:'user',id:a.collaborator_id,label:'Demo collaborator'};
 await api(a.owner_token,'POST',`/channels/${a.channel_id}/messages`,{client_message_id:randomUUID(),thread_id:root.thread_id,text:'@Demo collaborator hello',document:document(mention,mention.label)},201);
 assert.equal((await api(a.collaborator_token,'GET',`/workspaces/${a.workspace_id}/mentions`)).items.length,2);
 await api(a.owner_token,'POST',`/channels/${a.channel_id}/messages`,{client_message_id:randomUUID(),text:'@Demo collaborator',document:{ops:[{insert:'@Demo collaborator',attributes:{mention}},{insert:'\n',attributes:{'code-block':true}}]}},201);
 assert.equal((await api(a.collaborator_token,'GET',`/workspaces/${a.workspace_id}/mentions`)).items.length,2);
});
