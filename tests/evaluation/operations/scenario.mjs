import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import { indexMessage } from '@space/server/search';
import { SearchStore } from '@space/postgres/search';
import { agentLifecycle, channelMemory, workspaceTools } from './workspace-tools.mjs';
import { attachments } from './attachments.mjs';
import { huddles } from './huddles.mjs';
import { connections } from './connections.mjs';
import { realtime } from './realtime.mjs';

export async function scenario(ctx) {
  const { client, round, emails, origin } = ctx;
  const owner = client('192.0.2.' + round), peer = client('198.51.100.' + round);
  const password = 'Bench-' + randomUUID();
  const email = randomUUID() + '@example.test';
  const auth = (who, op, method, path, ...rest) => who.call('Authentication', op, method, '/v1/auth/' + path, ...rest);
  const signup = (who, email) => auth(who, 'Sign up', 'POST', 'sign-up/email', { email, name: 'Bench', password });
  const { user } = await signup(owner, email);
  const peerUser = (await signup(peer, randomUUID() + '@example.test')).user;
  await auth(owner, 'Sign in', 'POST', 'sign-in/email', { email, password });
  assert.equal((await auth(owner, 'Restore session', 'GET', 'get-session')).user.id, user.id);
  await auth(owner, 'Refresh session', 'POST', 'refresh', {});
  await auth(owner, 'Request verification email', 'POST', 'send-verification-email', { email, callbackURL: origin + '/chat' });
  const link = new URL(emails.get(email));
  await owner.call('Authentication', 'Verify email', 'GET', link.pathname + link.search, undefined, 302);
  assert.equal((await auth(owner, 'Restore verified session', 'GET', 'get-session')).user.emailVerified, true);
  const call = (area, who = owner) => (op, method, path, ...rest) => who.call(area, op, method, '/v1' + path, ...rest);
  const w = call('Workspace'), c = call('Channels'), m = call('Messages'), p = call('User Profiles');
  const wp = call('Workspace', peer), cp = call('Channels', peer), mp = call('Messages', peer);
  await p('My profile', 'GET', '/me');
  await p('Edit profile', 'PATCH', '/me', { full_name: 'Benchmark Person', title: 'Engineer', time_zone: 'UTC' });
  const photo = 'data:image/jpeg;base64,/9j/AA==';
  await p('Set profile photo', 'PATCH', '/me', { image: photo });
  await p('Remove profile photo', 'PATCH', '/me', { image: null });
  await p('Set presence', 'PATCH', '/me', { presence: 'away' });
  await p('Set status', 'PATCH', '/me', { status: { text: 'Testing', emoji: '🔬', expires_at: null } });
  await p('Clear status', 'PATCH', '/me', { status: null });
  const ws = (await w('Create', 'POST', '/workspaces', { name: 'Bench' }, 201)).id;
  const base = '/workspaces/' + ws, hub = base + '/hub';
  await w('List', 'GET', '/workspaces');
  await w('Details', 'GET', base);
  await w('Rename', 'PATCH', base, { name: 'Benchmark workspace' });
  const settings = await w('Read settings', 'GET', base + '/settings');
  const slug = 'bench-' + randomUUID().slice(0, 12);
  await w('Update settings', 'PATCH', base + '/settings', { revision: settings.revision, slug, approved_email_domains: ['example.test'] });
  await w('Resolve slug', 'GET', '/workspaces/by-slug/' + slug);
  const peerWs = (await wp('Create', 'POST', '/workspaces', { name: 'Peer workspace' }, 201)).id;
  const peerSettings = '/workspaces/' + peerWs + '/settings';
  const peerRevision = (await wp('Read settings', 'GET', peerSettings)).revision;
  const peerSlug = slug + '-peer';
  await wp('Update settings', 'PATCH', peerSettings, { revision: peerRevision, slug: peerSlug, approved_email_domains: ['example.test'] });
  await w('Join by email domain', 'POST', '/workspaces/by-slug/' + peerSlug + '/join', {});
  const invitations = base + '/invitations';
  const createInvite = (fields) => w('Create invitation', 'POST', invitations, { request_id: randomUUID(), ...fields }, 201);
  const revoked = await createInvite({ email: 'unused@example.test' });
  await w('Resend invitation', 'POST', invitations + '/' + revoked.invitation.id + '/resend', { request_id: randomUUID() });
  await w('Revoke invitation', 'DELETE', invitations + '/' + revoked.invitation.id, undefined, 204);
  const invite = await createInvite({ kind: 'link' });
  await w('List invitations', 'GET', invitations);
  await wp('Preview invitation', 'GET', '/invitations/' + invite.token);
  await wp('Accept invitation', 'POST', '/invitations/' + invite.token + '/accept', {});
  await w('Members', 'GET', base + '/members');
  await w('Directory', 'GET', base + '/directory');
  await w('Export members CSV', 'GET', base + '/members.csv');
  await w('Change member role', 'PATCH', base + '/members/' + peerUser.id, { role: 'admin' });
  assert.equal((await p('View member profile', 'GET', base + '/profiles/user/' + peerUser.id)).id, peerUser.id);
  const pairing = await w('Create agent pairing', 'POST', base + '/agent-pairings', {}, 201);
  const agent = await w('Claim agent pairing', 'POST', '/agent-pairings/claim', { code: pairing.code, credential: randomBytes(32).toString('base64url') }, 201);
  await p('View agent profile', 'GET', base + '/profiles/agent/' + agent.installation_id);
  await w('Participants', 'GET', base + '/participants');
  const channel = (await c('Create', 'POST', base + '/channels', { name: 'bench-channel', private: false }, 201)).id;
  const ch = '/channels/' + channel;
  await c('List', 'GET', base + '/channels');
  await c('Details', 'GET', ch);
  await c('Location', 'GET', ch + '/location');
  await c('Edit details', 'PATCH', ch, { topic: 'Performance' });
  await c('Archive', 'PATCH', ch, { archived: true });
  await c('Restore', 'PATCH', ch, { archived: false });
  await c('Add member', 'POST', ch + '/members', { user_id: peerUser.id }, 201);
  await c('List members', 'GET', ch + '/members');
  await c('Remove member', 'DELETE', ch + '/members/' + peerUser.id, undefined, 204);
  await cp('Join', 'POST', ch + '/join', {});
  const permissions = await c('Read permissions', 'GET', ch + '/permissions');
  await c('Update permissions', 'PATCH', ch + '/permissions', { revision: permissions.revision, posting: 'members' });
  await c('Tabs', 'GET', ch + '/tabs');
  await c('Reorder tabs', 'PUT', ch + '/tabs/order', { tab: 'pins', target: 'files', side: 'before' }, 204);
  await c('Set tab visibility', 'PUT', ch + '/tabs/pins', { visible: true }, 204);
  await c('Links', 'GET', ch + '/links');
  const hook = await c('Create webhook', 'POST', ch + '/webhooks', { name: 'Build' }, 201);
  await c('List webhooks', 'GET', ch + '/webhooks');
  await owner.call('Channels', 'Post incoming webhook', 'POST', hook.path, { text: 'Build' }, 200, { 'idempotency-key': randomUUID() });
  await c('Revoke webhook', 'DELETE', ch + '/webhooks/' + hook.id, undefined, 204);
  const section = randomUUID(), sections = base + '/sidebar-sections';
  await w('Create sidebar section', 'POST', sections, { id: section, name: 'Bench' }, 201);
  await w('List sidebar sections', 'GET', sections);
  await w('Rename sidebar section', 'PATCH', sections + '/' + section, { name: 'Bench work' });
  await w('Assign sidebar section', 'PUT', base + '/sidebar-section-assignments/' + channel, { section_id: section });
  await w('Delete sidebar section', 'DELETE', sections + '/' + section);
  await c('Star channel', 'POST', hub + '/starred/' + channel, { active: true });
  await c('Channel star state', 'GET', hub + '/starred/' + channel);
  await c('List starred channels', 'GET', hub + '/starred');
  await mp('Notification preferences', 'GET', base + '/notification-settings');
  await mp('Update notifications', 'PATCH', base + '/notification-settings', { mode: 'all', desktop_enabled: true });
  await cp('Channel notification settings', 'PATCH', ch + '/notification-settings', { mode: 'all' });
  await m('Mention preferences', 'GET', base + '/mention-settings');
  await m('Update mention preferences', 'PATCH', base + '/mention-settings', { broadcast_permission: 'admins' });
  await m('Mention candidates', 'GET', ch + '/mentions?q=Bench');
  await m('Mention detail', 'GET', ch + '/mentions/user/' + peerUser.id);
  const root = await m('Send', 'POST', ch + '/messages', { client_message_id: randomUUID(), text: 'Performance' }, 201);
  const source = ch + '/messages/' + root.id, thread = '/threads/' + root.thread_id;
  await m('Edit', 'PATCH', source, { revision: root.reaction_sequence ?? '0', document: { ops: [{ insert: 'Edited performance' }] } });
  await indexMessage(new SearchStore(ctx.pool), ctx.engine, root.id, channel);
  assert.ok((await m('Search', 'GET', base + '/search?q=performance')).items.some(hit => hit.id === root.id));
  const reply = await mp('Reply', 'POST', ch + '/messages', { client_message_id: randomUUID(), text: 'A reply', thread_id: root.thread_id }, 201);
  await mp('Broadcast reply', 'PUT', ch + '/messages/' + reply.id + '/broadcast', {});
  await m('Read message', 'GET', source);
  await m('Channel timeline', 'GET', ch + '/messages');
  await m('Replay channel events', 'GET', ch + '/history');
  await m('Thread history', 'GET', thread + '/history');
  await m('Thread messages', 'GET', thread + '/messages');
  await m('Follow state', 'GET', thread + '/notification-subscription');
  await m('Follow thread', 'PATCH', thread + '/notification-subscription', { following: true });
  await m('Threads', 'GET', hub + '/threads');
  const ht = hub + thread;
  await m('Earlier replies', 'GET', ht + '/replies?before=' + (Number(reply.sequence) + 1));
  await m('Mark thread read', 'POST', ht + '/read', { sequence: reply.sequence });
  await m('Mark thread unread', 'POST', ht + '/unread', { sequence: reply.sequence });
  if (process.env.XAI_API_KEY) {
    const result = await m('Generate reply suggestion', 'POST', thread + '/reply-suggestion', {});
    assert.ok(result.suggestion, 'Model produced no suggestion');
  }
  await m('Add reaction', 'POST', source + '/reactions', { emoji: '👍', active: true });
  await m('Remove reaction', 'POST', source + '/reactions', { emoji: '👍', active: false });
  await c('Pin message', 'PUT', ch + '/pins/' + root.id, {}, 204);
  await c('List pins', 'GET', ch + '/pins');
  await c('Unpin message', 'DELETE', ch + '/pins/' + root.id, undefined, 204);
  const todo = hub + '/todos/' + randomUUID();
  await w('Create workspace to-do', 'POST', todo, { title: 'Benchmark', completed: false });
  await w('View workspace to-do', 'GET', todo);
  await w('List workspace to-dos', 'GET', hub + '/todos');
  await w('Clean up workspace to-dos', 'POST', hub + '/todos/cleanup', { action: 'complete', scope: 'all' });
  const session = randomUUID();
  await ctx.pool.query('INSERT INTO agent_sessions(id,workspace_id,installation_id,origin_thread_id,title,managed) VALUES($1,$2,$3,$4,$5,true)',
    [session, ws, agent.installation_id, root.thread_id, 'Benchmark']);
  await w('Star session', 'POST', hub + '/starred-sessions/' + session, { active: true });
  await w('Session star state', 'GET', hub + '/starred-sessions/' + session);
  await w('List starred sessions', 'GET', hub + '/starred-sessions');
  await m('Sent messages', 'GET', hub + '/sent');
  await m('Save message', 'POST', hub + '/saved/' + root.id, { channel_id: channel, active: true });
  await m('Saved messages', 'GET', hub + '/saved');
  await m('Saved state', 'POST', hub + '/saved/state/' + channel, { ids: [root.id] });
  await m('Clear saved messages', 'POST', hub + '/saved/cleanup', { action: 'clear' });
  await m('Send mention', 'POST', ch + '/messages', { client_message_id: randomUUID(), text: '@Bench hello',
    document: { ops: [{ insert: '@Bench', attributes: { mention: { kind: 'user', id: peerUser.id, label: 'Bench' } } }, { insert: ' hello\n' }] } }, 201);
  const mentions = await mp('Mentions', 'GET', base + '/mentions');
  await mp('Read mention', 'POST', base + '/mentions/' + mentions.items[0].id + '/read', {});
  const activity = await mp('Notification activity', 'GET', base + '/notifications');
  const notice = base + '/notifications/' + activity.items[0].id;
  await mp('Claim notification', 'POST', notice + '/claim', {});
  await mp('Mark notification read', 'PATCH', notice, { read: true });
  await mp('Mark notifications read', 'POST', base + '/notifications/read', { through: activity.latest_id });
  await mp('Unread counts', 'GET', base + '/unread');
  await mp('Mark channel read', 'POST', ch + '/read', { sequence: reply.sequence });
  await m('Cancel outgoing', 'DELETE', ch + '/outgoing/' + randomUUID());
  const later = new Date(Date.now() + 3600000).toISOString();
  const scheduled = await m('Schedule message', 'POST', ch + '/scheduled-messages', { id: randomUUID(), text: 'Later', send_at: later }, 201);
  await m('List scheduled', 'GET', base + '/scheduled-messages');
  const sp = '/scheduled-messages/' + scheduled.id;
  await m('Reschedule', 'PATCH', sp, { send_at: new Date(Date.now() + 7200000).toISOString() });
  await m('Cancel scheduled', 'DELETE', sp);
  const draft = '/composer-drafts/' + channel;
  const put = base => m('Save draft', 'PUT', draft, { base, mutation_id: randomUUID(), value: { document: { ops: [{ insert: 'Draft' }] }, files: [] } });
  const first = await put(null);
  await m('List drafts', 'GET', '/composer-drafts');
  await m('Get draft', 'GET', draft);
  await m('Send draft', 'POST', draft + '/send', { revision: first.revision }, 204);
  const next = await put((await m('Get draft', 'GET', draft)).revision);
  await m('Schedule draft', 'POST', draft + '/schedule', { revision: next.revision, send_at: later }, 204);
  const pending = await m('List scheduled', 'GET', base + '/scheduled-messages');
  await m('Send scheduled now', 'POST', '/scheduled-messages/' + pending.items[0].id + '/send', {});
  await mp('Delete message', 'DELETE', ch + '/messages/' + reply.id);
  await m('DM directory', 'GET', base + '/direct-message-people');
  const dm = await m('Open DM', 'POST', base + '/direct-messages', { user_id: peerUser.id });
  await m('List DMs', 'GET', base + '/direct-messages');
  await m('Hide DM', 'PATCH', '/channels/' + dm.id + '/direct-message', { hidden: true });
  await realtime(ctx, owner, peer, ws, channel);
  await attachments(ctx, { owner, peer, call, channel, ws, dm: dm.id });
  await workspaceTools({owner, call, ws, channel, thread});
  await channelMemory(ctx, {call, channel, thread, session, messageId: root.id, installation: agent.installation_id});
  await w('List workflows', 'GET', base + '/workflows');
  await call('Huddles')('Configuration', 'GET', '/huddles/config');
  if (ctx.media) await huddles({call, ws, channel, peer, peerId: peerUser.id, media: ctx.media});
  await connections(call, ws, agent.installation_id);
  await agentLifecycle({call, ws, channel, thread, dm: dm.id, messageId: root.id, peer, peerId: peerUser.id, installation: agent.installation_id, pairing: pairing.id});
  await w('Remove member', 'DELETE', base + '/members/' + peerUser.id, undefined, 204);
  await w('Add member', 'POST', base + '/members', { user_id: peerUser.id, role: 'member' }, 201);
  await w('Transfer ownership', 'POST', base + '/transfer-ownership', { user_id: peerUser.id });
  await auth(owner, 'Sign out', 'POST', 'sign-out', {});
}
