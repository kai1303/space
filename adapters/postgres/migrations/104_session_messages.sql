CREATE TABLE agent_session_inputs (
 id uuid PRIMARY KEY, session_id uuid NOT NULL REFERENCES agent_sessions(id) ON DELETE CASCADE,
 actor_id uuid NOT NULL REFERENCES users(id), kind text NOT NULL CHECK(kind IN ('queue','steer')),
 execution_id uuid, body jsonb NOT NULL, request_hash text NOT NULL,
 state text NOT NULL CHECK(state IN ('pending','blocked','sent','cancelled','sending','uncertain')),
 position bigint GENERATED BY DEFAULT AS IDENTITY, task_id uuid REFERENCES tasks(id), detail text,
 created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE assets ADD COLUMN queue_input_id uuid REFERENCES agent_session_inputs(id) ON DELETE SET NULL;
ALTER TABLE assets ADD CONSTRAINT asset_queue_owner CHECK (queue_input_id IS NULL OR (task_id IS NULL AND message_id IS NULL AND status='ready'));
CREATE INDEX assets_queue_input ON assets(queue_input_id) WHERE queue_input_id IS NOT NULL;
CREATE INDEX session_inputs_pending ON agent_session_inputs(session_id,position) WHERE kind='queue' AND state IN ('pending','blocked');
CREATE INDEX session_inputs_execution ON agent_session_inputs(session_id,execution_id) WHERE kind='steer';
CREATE FUNCTION session_input_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 UPDATE agent_sessions SET revision=revision+1 WHERE id=NEW.session_id;
 IF NEW.kind='steer' AND NEW.state='sending' THEN
   INSERT INTO event_outbox(kind,aggregate_id,payload,available_at) VALUES ('task.steer_deadline',NEW.id::text,'{}',now()+interval '30 seconds');
 END IF;
 IF NEW.kind='queue' AND NEW.state='cancelled' THEN
   UPDATE assets SET queue_input_id=NULL, expires_at=now()+interval '1 day' WHERE queue_input_id=NEW.id;
 END IF;
 IF NEW.kind='queue' AND (NEW.state='pending' OR (TG_OP='UPDATE' AND NEW.state='cancelled')) THEN
   INSERT INTO event_outbox(kind,aggregate_id,payload) VALUES ('task.session_queue',NEW.session_id::text,'{}');
 END IF;
 RETURN NULL;
END; $$;
CREATE TRIGGER session_input_changed AFTER INSERT OR UPDATE ON agent_session_inputs FOR EACH ROW EXECUTE FUNCTION session_input_changed();
CREATE FUNCTION wake_session_input() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.session_id IS NOT NULL AND NEW.status<>OLD.status AND NEW.status IN ('completed','failed','rejected')
 THEN
   INSERT INTO event_outbox(kind,aggregate_id,payload) VALUES ('task.session_queue',NEW.session_id::text,'{}');
 END IF;
 RETURN NULL;
END; $$;
CREATE TRIGGER wake_session_input AFTER UPDATE OF status ON tasks FOR EACH ROW EXECUTE FUNCTION wake_session_input();
